create table if not exists public.fraud_subjects (
  id uuid primary key default gen_random_uuid(),
  subject_type text not null check (subject_type in ('user','location','claim','organizer','event','experience','reservation','order','payment','payout','review','other')),
  subject_id text not null,
  display_label text,
  risk_score integer not null default 0 check (risk_score between 0 and 100),
  risk_band text not null default 'low' check (risk_band in ('low','guarded','elevated','high','critical')),
  enforcement_state text not null default 'none' check (enforcement_state in ('none','limited','suspended','banned')),
  active_case_id uuid,
  first_seen_at timestamptz not null default now(),
  last_signal_at timestamptz,
  last_reviewed_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(subject_type, subject_id)
);

