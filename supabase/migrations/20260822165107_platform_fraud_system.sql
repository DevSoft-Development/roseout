create or replace function public.fraud_risk_band(score integer)
returns text
language sql
immutable
security invoker
set search_path = public, pg_temp
as $$
  select case
    when score >= 85 then 'critical'
    when score >= 65 then 'high'
    when score >= 40 then 'elevated'
    when score >= 20 then 'guarded'
    else 'low'
  end;
$$;

create or replace function public.fraud_recalculate_subject(p_subject_type text, p_subject_id text)
returns public.fraud_subjects
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_score integer;
  v_subject public.fraud_subjects;
begin
  select greatest(0, least(100, coalesce(round(sum(score_delta * confidence))::integer, 0)))
  into v_score
  from public.fraud_signals
  where subject_type = p_subject_type
    and subject_id = p_subject_id
    and (expires_at is null or expires_at > now());

  insert into public.fraud_subjects(subject_type, subject_id, risk_score, risk_band, last_signal_at)
  values (p_subject_type, p_subject_id, v_score, public.fraud_risk_band(v_score), now())
  on conflict (subject_type, subject_id) do update set
    risk_score = excluded.risk_score,
    risk_band = excluded.risk_band,
    last_signal_at = excluded.last_signal_at,
    updated_at = now()
  returning * into v_subject;
  return v_subject;
end;
$$;

create or replace function public.fraud_ensure_case(p_subject_type text, p_subject_id text, p_reason text default null)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_subject public.fraud_subjects;
  v_case_id uuid;
  v_priority text;
begin
  select * into v_subject from public.fraud_subjects
  where subject_type = p_subject_type and subject_id = p_subject_id;

  if v_subject.id is null then
    v_subject := public.fraud_recalculate_subject(p_subject_type, p_subject_id);
  end if;

  if v_subject.active_case_id is not null then
    update public.fraud_cases
    set risk_score = v_subject.risk_score, last_activity_at = now(), updated_at = now()
    where id = v_subject.active_case_id and status <> 'closed';
    if found then return v_subject.active_case_id; end if;
  end if;

  v_priority := case
    when v_subject.risk_score >= 85 then 'urgent'
    when v_subject.risk_score >= 65 then 'high'
    when v_subject.risk_score >= 40 then 'medium'
    else 'low'
  end;

  insert into public.fraud_cases(primary_subject_type, primary_subject_id, title, summary, priority, risk_score)
  values (
    p_subject_type,
    p_subject_id,
    initcap(p_subject_type) || ' fraud review · ' || p_subject_id,
    coalesce(p_reason, 'Automatically opened from fraud risk signals.'),
    v_priority,
    v_subject.risk_score
  ) returning id into v_case_id;

  insert into public.fraud_case_subjects(case_id, subject_type, subject_id, relationship)
  values (v_case_id, p_subject_type, p_subject_id, 'primary')
  on conflict do nothing;

  update public.fraud_subjects set active_case_id = v_case_id, updated_at = now()
  where subject_type = p_subject_type and subject_id = p_subject_id;

  insert into public.fraud_audit_log(case_id, subject_type, subject_id, event_type, payload)
  values (v_case_id, p_subject_type, p_subject_id, 'case_opened', jsonb_build_object('reason', p_reason, 'risk_score', v_subject.risk_score));
  return v_case_id;
end;
$$;

create or replace function public.fraud_after_signal()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_subject public.fraud_subjects;
  v_auto_case boolean;
begin
  v_subject := public.fraud_recalculate_subject(new.subject_type, new.subject_id);
  select coalesce(auto_case, true) into v_auto_case from public.fraud_rules where rule_key = new.rule_key;
  if v_auto_case is null then v_auto_case := true; end if;

  if v_auto_case and (v_subject.risk_score >= 40 or new.severity >= 4) then
    perform public.fraud_ensure_case(new.subject_type, new.subject_id, 'Opened automatically after ' || new.signal_type || ' signal.');
  end if;

  insert into public.fraud_audit_log(subject_type, subject_id, event_type, payload)
  values (new.subject_type, new.subject_id, 'signal_recorded', jsonb_build_object('signal_id', new.id, 'signal_type', new.signal_type, 'score_delta', new.score_delta));
  return new;
end;
$$;

